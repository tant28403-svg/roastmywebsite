from __future__ import annotations

import re

# WAF signatures: (name, header_patterns, cookie_patterns, body_patterns)
WAF_SIGNATURES = [
    ("Cloudflare", ["cf-ray", "cf-cache-status"], ["__cf_bm", "cf_clearance"], ["Attention Required", "Cloudflare", "cf-browser-verification"]),
    ("AWS WAF", ["x-amzn-requestid", "x-amz-cf-id"], [], ["Request blocked", "AWS WAF"]),
    ("ModSecurity", ["x-mod-security", "mod_security"], [], ["ModSecurity", "This error was generated by Mod_Security"]),
    ("Imperva/Incapsula", ["x-iinfo", "x-cdn"], ["incap_ses_", "visid_incap_"], ["Incapsula", "imperva"]),
    ("Sucuri", ["x-sucuri-id", "x-sucuri-cache"], ["sucuri_cloudproxy_uuid"], ["Sucuri", "Access Denied - Sucuri"]),
    ("Akamai", ["x-akamai-transformed", "akamai-grn"], ["ak_bmsc", "bm_sz"], ["Akamai", "Reference #"]),
    ("F5 BIG-IP ASM", ["x-wa-info", "x-cnection"], ["TS", "BIGipServer"], ["The requested URL was rejected", "F5"]),
    ("Barracuda", ["barra_counter_session"], ["BNI"], ["Barracuda"]),
    ("Fortinet FortiWeb", [], [], ["FortiWeb", "Fortinet"]),
    ("Citrix NetScaler", ["ns-cache"], ["nsC", "citrix_ns_id"], ["NetScaler"]),
]


def detect_waf(headers: dict[str, str], body: str = "", cookies: str = "") -> str | None:
    """Detect WAF from response headers, body, and cookies. Returns WAF name or None."""
    headers_lower = {k.lower(): v.lower() for k, v in headers.items()}
    body_lower = (body or "").lower()
    cookies_lower = (cookies or "").lower()

    for name, header_pats, cookie_pats, body_pats in WAF_SIGNATURES:
        # Check headers
        for pat in header_pats:
            if any(pat.lower() in k or pat.lower() in v for k, v in headers_lower.items()):
                return name
        # Check cookies
        for pat in cookie_pats:
            if pat.lower() in cookies_lower:
                return name
        # Check body
        for pat in body_pats:
            if pat.lower() in body_lower:
                return name
    return None


def is_blocked(status_code: int, body: str = "") -> bool:
    """Check if response indicates blocking."""
    if status_code in (403, 429, 503, 406, 419):
        return True
    body_lower = (body or "").lower()
    block_indicators = [
        "access denied", "blocked", "forbidden", "captcha", "challenge",
        "attention required", "security check", "bot detection",
        "rate limit", "too many requests",
    ]
    return any(ind in body_lower for ind in block_indicators)


def is_captcha(body: str = "") -> bool:
    """Check if response contains a CAPTCHA challenge."""
    body_lower = (body or "").lower()
    captcha_indicators = [
        "recaptcha", "hcaptcha", "turnstile", "cf-challenge",
        "captcha", "g-recaptcha", "h-captcha",
    ]
    return any(ind in body_lower for ind in captcha_indicators)


def waf_adapt_payload(payload: str, waf_type: str | None) -> list[str]:
    """Return WAF-specific adapted payloads."""
    if not waf_type:
        return [payload]

    variants = [payload]
    waf_lower = (waf_type or "").lower()

    if "cloudflare" in waf_lower:
        # MySQL version comments
        variants.append(payload.replace("SELECT", "/*!50000SELECT*/"))
        variants.append(payload.replace("UNION", "/*!50000UNION*/"))
        variants.append(payload.replace(" ", "/**/"))
    elif "modsecurity" in waf_lower or "mod_security" in waf_lower:
        variants.append(payload.replace("SELECT", "/*!30000SELECT*/"))
        variants.append(payload.replace(" ", "/**/"))
    elif "aws" in waf_lower:
        # Unicode normalization
        variants.append(payload.replace(" ", "\u00a0"))
        # Case randomization is handled by encoding module
    elif "imperva" in waf_lower or "incapsula" in waf_lower:
        variants.append(payload.replace(" ", "/**/"))
        variants.append(payload.replace("'", "\uff07"))  # fullwidth apostrophe

    # Deduplicate
    seen = set()
    result = []
    for v in variants:
        if v not in seen:
            seen.add(v)
            result.append(v)
    return result